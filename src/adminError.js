export function adminError(error) {
  if (error?.code === "42501" || error?.status === 403) return "Доступ запрещён. Требуется закреплённый аккаунт администратора; проверьте, что он не заблокирован.";
  if (["28000", "PGRST301", "PGRST303"].includes(error?.code) || error?.status === 401) return "Сессия истекла. Войдите в аккаунт заново.";
  if (error?.code === "22023") return "Проверьте параметры и причину действия. Причина должна содержать 3–200 символов без секретов.";
  if (error?.code === "P0002") return "Объект больше недоступен или уже изменён. Обновите список.";
  return "Не удалось выполнить запрос. Проверьте соединение и повторите попытку.";
}
